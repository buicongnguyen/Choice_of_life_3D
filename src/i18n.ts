export type UIKey = keyof typeof EN_UI;

export let lang: Lang = "en";
let dict: Record<string, string> = EN_UI;

export function setUI(code: Lang, table?: Partial<Record<UIKey, string>>) {
  lang = code;
  dict = { ...EN_UI, ...(table ?? {}) };
}

export function u(key: UIKey, vars?: Record<string, string | number>) {
  const s = dict[key] ?? EN_UI[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s;
}

/** Preferred language: a saved choice, else the browser's, else English. */
export function pickLang(saved: unknown): Lang {
  if (saved === "en" || saved === "vi" || saved === "ko") return saved;
  const nav = (typeof navigator !== "undefined" ? navigator.language : "en").toLowerCase();
  return nav.startsWith("vi") ? "vi" : nav.startsWith("ko") ? "ko" : "en";
}
